import { cp, mkdir, rm } from 'node:fs/promises';
import path from 'node:path';
const root = path.resolve(import.meta.dirname, '..');
const output = path.join(root, '.api-assets');
await rm(output, { recursive: true, force: true });
await mkdir(path.join(output, 'content'), { recursive: true });
await mkdir(path.join(output, 'widgets'), { recursive: true });
await mkdir(path.join(output, 'trust'), { recursive: true });
await cp(path.join(root, 'content', 'catalog.json'), path.join(output, 'catalog.json'));
await cp(path.join(root, 'content', 'content-record.schema.json'), path.join(output, 'content', 'content-record.schema.json'));
await cp(path.join(root, 'widgets', 'lessons.js'), path.join(output, 'widgets', 'lessons.js'));
await cp(path.join(root, 'widgets', 'business-pathways.js'), path.join(output, 'widgets', 'business-pathways.js'));
await cp(path.join(root, 'widgets', 'business-experience.js'), path.join(output, 'widgets', 'business-experience.js'));
await cp(path.join(root, 'widgets', 'government-services.js'), path.join(output, 'widgets', 'government-services.js'));
await cp(path.join(root, 'widgets', 'powered-by-brasa.js'), path.join(output, 'widgets', 'powered-by-brasa.js'));
for (const file of ['status.json','powered-by-brasa.html','powered-by-brasa.css','powered-by-brasa.js']) await cp(path.join(root, 'trust', file), path.join(output, 'trust', file));
await cp(path.join(root, 'openapi.yaml'), path.join(output, 'openapi.yaml'));
console.log('Built minimal API asset bundle.');
